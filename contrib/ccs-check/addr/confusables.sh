#!/usr/bin/env bash
# confusables.sh FILE: write confusables.go from Unicode's confusables.txt (TR39, FILE): each
# single non-ASCII character that Unicode says is confusable with one ASCII letter or digit.
# Run it again when Unicode updates the file, and commit the result. Needs gawk.
set -euo pipefail
f=$1
here=$(dirname "$(readlink -f "$0")")
version=$(gawk '/^# Version:/ { print $3; exit }' "$f")
sum=$(sha256sum "$f" | gawk '{ print $1 }')
{
    printf '// Code generated by confusables.sh from confusables.txt %s (sha256 %s). DO NOT EDIT.\n\n' "$version" "$sum"
    printf 'package addr\n\n'
    printf '// confusables maps each non-ASCII character that Unicode (TR39) lists as confusable with a\n'
    printf '// single ASCII letter or digit to that letter or digit.\n'
    printf 'var confusables = map[rune]byte{\n'
    LC_ALL=C gawk -F ' ;\t' '
        /^[0-9A-F]+ ;\t[0-9A-F]+ ;\t/ {
            s = strtonum("0x" $1); t = strtonum("0x" $2)
            if (s >= 128 && (t >= 48 && t <= 57 || t >= 65 && t <= 90 || t >= 97 && t <= 122))
                printf "%06X\t0x%04X: \047%c\047,\n", s, s, t
        }' "$f" | sort | cut -f 2 | sed 's/^/\t/'
    printf '}\n'
} > "$here/confusables.go"
