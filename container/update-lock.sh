#!/usr/bin/env bash
# update-lock.sh: write deps.lock, the exact .deb files ccs-bash needs on top of the
# pinned base image: "sha256 size url", the urls on snapshot.debian.org, which keeps
# every file forever.
#
# This is the only step that uses apt, and only to work out what to download; run it
# when changing the pin (base-image, snapshot or packages). Fetching and building use
# deps.lock alone.
set -euo pipefail
here=$(dirname "$(readlink -f "$0")")
base=$(cat "$here/base-image")
snapshot=$(cat "$here/snapshot")
mapfile -t packages < <(grep -v '^#' "$here/packages")

docker run --rm -v "$here/resolve.sh:/resolve.sh:ro" "$base" bash /resolve.sh "$snapshot" "${packages[@]}" \
    > "$here/deps.lock.new"
[[ -s $here/deps.lock.new ]] || { echo "nothing resolved" >&2; exit 1; }

# Add the mirrors that serve each file with the right sha256 (downloaded and checked,
# not just looked up). Every file needs snapshot.debian.org plus at least 2 mirrors.
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
while read -r sum size url; do
    path=${url#*/"$snapshot"/}                  # pool/main/q/qrencode/...
    archive=${url#https://snapshot.debian.org/archive/}
    archive=${archive%%/*}                      # debian or debian-security
    urls=$url
    while read -r a base; do
        [[ $a == "$archive" ]] || continue
        if curl -fsSL --max-time 300 -o "$tmp/f" "$base/$path" && echo "$sum  $tmp/f" | sha256sum -c --status; then
            urls+=" $base/$path"
        fi
    done < <(grep -v '^#' "$here/mirrors")
    (($(wc -w <<<"$urls") >= 3)) || { echo "error: fewer than 2 mirrors serve $path" >&2; exit 1; }
    echo "$sum $size $urls"
done < "$here/deps.lock.new" | sort -k3 > "$tmp/lock"

{
    echo "# sha256 size url... (snapshot.debian.org first, then mirrors). Generated by update-lock.sh"
    echo "# from base-image, snapshot, packages and mirrors; fetch.sh tries the urls in order."
    cat "$tmp/lock"
} > "$here/deps.lock"
rm "$here/deps.lock.new"
echo "$(grep -vc '^#' "$here/deps.lock") files, $(awk '!/^#/ {s += $2} END {printf "%.1f MB", s / 1e6}' "$here/deps.lock")" >&2
